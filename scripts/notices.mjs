// Run before packaging. Keep this list aligned with third-party imports bundled into out/.
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { existsSync, realpathSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "apps/desktop/package.json"));
const bundled = ["react", "react-dom", "zustand", "immer", "lucide-react", "node-pty", "@pierre/diffs"];
const visited = new Set();
const sections = [];
function visit(name, resolver) {
  const candidate = resolver.resolve.paths(name)?.map((directory) => join(directory, name, "package.json")).find(existsSync);
  if (!candidate) throw new Error(`Cannot locate license for ${name}`);
  const path = realpathSync(candidate);
  const directory = dirname(path);
  const pkg = JSON.parse(readFileSync(path, "utf8"));
  const key = `${name}@${pkg.version}`;
  if (visited.has(key)) return;
  visited.add(key);
  const licenses = readdirSync(directory).filter((file) => /^(licen[cs]e|copying|notice)(\..*)?$/i.test(file));
  if (!licenses.length && name === "lru_map") {
    const readme = readFileSync(join(directory, "README.md"), "utf8");
    const start = readme.indexOf("# MIT license");
    if (start < 0) throw new Error(`Missing license text for ${key}`);
    sections.push(`## ${key} (MIT)\n\n${readme.slice(start).trim()}`);
  } else if (!licenses.length) throw new Error(`Missing license text for ${key}`);
  if (licenses.length) sections.push(`## ${key} (${pkg.license ?? "see license"})\n\n` + licenses.map((file) => `### ${file}\n\n` + readFileSync(join(directory, file), "utf8").trim()).join("\n\n"));
  for (const dependency of Object.keys(pkg.dependencies ?? {}).sort()) visit(dependency, createRequire(path));
}
for (const name of bundled) visit(name, require);
const header = `# Third-party notices\n\nOcto is MIT licensed. The software below retains its own licenses. This file is generated by scripts/notices.mjs from the installed, locked packages bundled into the app and their dependencies.\n\nThe Electron runtime ships LICENSE.electron.txt and LICENSES.chromium.html inside the app bundle.\n`;
const vendored = [
  ["T3 Code terminal adapter (MIT), revision c79ef8c454e1268ff79da5a9dcb74572e86f7861", "apps/desktop/src/renderer/src/terminal/ghostty/LICENSE.t3"],
  ["libghostty-vt (MIT), revision 9f62873bf195e4d8a762d768a1405a5f2f7b1697", "native/libghostty-vt/LICENSE"],
  ["Symbols Nerd Font Mono (MIT)", "apps/desktop/src/renderer/src/terminal/ghostty/fonts/LICENSE"],
].map(([title, path]) => `## ${title}\n\n${readFileSync(join(root, path), "utf8").trim()}`);
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), header + "\n" + [...sections.sort(), ...vendored].join("\n\n") + "\n");
