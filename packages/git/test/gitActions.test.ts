import { existsSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { newID, type DiffScope } from "@octo/core";
import { canPush, GitService, hasStaged, HunkPatch, isUntracked, publishes, pushRemote, PullRequests, stashReference, supportsHunkStaging, UnifiedDiffParser, type ChangedFile } from "../src";
import { removeRoot, Repository } from "./helpers";

const roots: string[] = [];
afterEach(() => { while (roots.length) removeRoot(roots.pop()!); });
const numbered = Array.from({ length: 30 }, (_, i) => `line ${i + 1}`);

describe("Git actions", () => {
  it("quotes unusual names in patches and keeps the missing-newline note", () => {
    expect(HunkPatch.quoted("a/plain name.txt")).toBe("a/plain name.txt");
    expect(HunkPatch.quoted("a/quote\"tab\t.txt")).toBe("\"a/quote\\\"tab\\t.txt\"");
    expect(HunkPatch.quoted("a/café\u0001")).toBe("\"a/café\\001\"");
    const lines = UnifiedDiffParser.parse("@@ -1,2 +1,2 @@\n same\n-old\n+new\n\\ No newline at end of file\n@@ -9 +9 @@\n-x\n+y\n");
    const ids = HunkPatch.hunkIDs(lines);
    expect(ids.length).toBe(2);
    expect(HunkPatch.make("f.txt", lines, ids[0])).toBe("diff --git a/f.txt b/f.txt\n--- a/f.txt\n+++ b/f.txt\n@@ -1,2 +1,2 @@\n same\n-old\n+new\n\\ No newline at end of file\n");
    expect(HunkPatch.hunkIDContaining(lines.at(-1)!.id, lines)).toBe(ids[1]);
    expect(HunkPatch.make("f.txt", lines, lines[1].id)).toBeUndefined();
  });

  it("changes only the index when staging a hunk", async () => {
    const repo = await Repository.make(roots);
    const path = "Sources/file with spaces.swift";
    repo.write(path, numbered.join("\n") + "\n");
    await repo.commitAll("fixture");
    const edited = [...numbered]; edited[1] = "first change"; edited[27] = "second change";
    const working = edited.join("\n") + "\n";
    repo.write(path, working);
    const service = new GitService(), id = newID();
    let [file] = await service.changes(repo.root);
    expect(supportsHunkStaging(file, "working")).toBe(true);
    const snapshot = await service.snapshot(file, id, repo.root, "working");
    const hunks = HunkPatch.hunkIDs(snapshot.lines);
    expect(hunks.length).toBe(2);
    await service.applyHunk(snapshot, hunks[1], repo.root);
    const staged = await repo.run(["diff", "--cached"]);
    expect(staged).toContain("+second change"); expect(staged).not.toContain("+first change");
    const unstaged = await repo.run(["diff"]);
    expect(unstaged).toContain("+first change"); expect(unstaged).not.toContain("+second change");
    expect(repo.read(path)).toBe(working);
    await expect(service.applyHunk(snapshot, hunks[1], repo.root)).rejects.toThrow(/no longer matches/);
    [file] = await service.changes(repo.root);
    expect(supportsHunkStaging(file, "staged")).toBe(true);
    const stagedSnapshot = await service.snapshot(file, id, repo.root, "staged");
    await service.applyHunk(stagedSnapshot, HunkPatch.hunkIDs(stagedSnapshot.lines)[0], repo.root);
    expect(await repo.run(["diff", "--cached"])).toBe("");
    expect(repo.read(path)).toBe(working);
  });

  it("keeps scopes for file staging, discard and commit", async () => {
    const repo = await Repository.make(roots);
    repo.write("kept.txt", "base\n");
    repo.write("renamed-from.txt", "rename me\n");
    await repo.commitAll("fixture");
    const service = new GitService(), root = repo.root;
    repo.write("kept.txt", "staged\n");
    await service.stage(["kept.txt"], root);
    repo.write("kept.txt", "staged\nunstaged\n");
    repo.write("new.txt", "untracked\n");
    let files = await service.changes(root);
    await service.discardUnstaged(files, root);
    expect(repo.read("kept.txt")).toBe("staged\n");
    expect(existsSync(join(root, "new.txt"))).toBe(false);
    files = await service.changes(root);
    expect(files.map((f) => f.path)).toEqual(["kept.txt"]);
    expect([files[0].indexStatus, files[0].worktreeStatus]).toEqual(["M", " "]);
    await repo.run(["mv", "renamed-from.txt", "renamed-to.txt"]);
    files = await service.changes(root);
    const rename = files.find((f) => f.indexStatus === "R")!;
    expect(rename.originalPath).toBe("renamed-from.txt");
    await service.unstage([rename], root);
    expect((await service.changes(root)).filter(hasStaged).map((f) => f.path)).toEqual(["kept.txt"]);
    await service.stage(["renamed-from.txt", "renamed-to.txt"], root);
    await service.unstage((await service.changes(root)).filter((f) => f.path.startsWith("renamed")), root);
    repo.write("kept.txt", "staged\nstill unstaged\n");
    const summary = await service.commit("#12 Keep staged edits\n\nBody line.\n", root);
    expect(summary.subject).toBe("#12 Keep staged edits");
    expect(summary.hash).not.toBe("");
    expect(await repo.run(["show", "HEAD:kept.txt"])).toBe("staged\n");
    expect(repo.read("kept.txt")).toBe("staged\nstill unstaged\n");
    expect((await service.changes(root)).some((f) => hasStaged(f) && f.path === "kept.txt")).toBe(false);
    await expect(service.commit("  \n", root)).rejects.toThrow();
  });

  it("unstages before the first commit and treats pathspecs literally", async () => {
    const repo = await Repository.make(roots);
    repo.write("*.txt", "star\n");
    repo.write("other.txt", "other\n");
    const service = new GitService(), root = repo.root;
    await service.stage(["*.txt"], root);
    let files = await service.changes(root);
    expect(files.filter(hasStaged).map((f) => f.path)).toEqual(["*.txt"]);
    await service.unstage(files.filter(hasStaged), root);
    files = await service.changes(root);
    expect(files.every(isUntracked)).toBe(true);
    const status = await service.upstreamStatus(root);
    expect(status.branch).toBe("main"); expect(status.hasCommits).toBe(false); expect(canPush(status)).toBe(false);
  });

  it("restores staging from named stashes and detects shifted references", async () => {
    const repo = await Repository.make(roots);
    repo.write("a.txt", "base\n");
    await repo.commitAll("fixture");
    const service = new GitService(), root = repo.root;
    repo.write("a.txt", "staged\n");
    await service.stage(["a.txt"], root);
    repo.write("a.txt", "staged\nworking\n");
    repo.write("untracked.txt", "new\n");
    await service.stash("WIP: native Git actions", true, root);
    expect(await service.changes(root)).toEqual([]);
    let stashes = await service.stashes(root);
    expect(stashes.length).toBe(1);
    expect(stashes[0].message).toBe("WIP: native Git actions");
    expect(stashes[0].branch).toBe("main");
    const first = stashes[0];
    await service.applyStash(first, false, root);
    let files = await service.changes(root);
    const restored = files.find((f) => f.path === "a.txt")!;
    expect([restored.indexStatus, restored.worktreeStatus]).toEqual(["M", "M"]);
    expect(files.some((f) => f.path === "untracked.txt" && isUntracked(f))).toBe(true);
    expect(await repo.run(["show", ":a.txt"])).toBe("staged\n");
    expect((await service.stashes(root)).length).toBe(1);
    await service.stash("Second", true, root);
    await expect(service.dropStash(first, root)).rejects.toThrow(/changed/);
    stashes = await service.stashes(root);
    expect(stashes.map((s) => s.message)).toEqual(["Second", "WIP: native Git actions"]);
    await service.applyStash(stashes[0], true, root);
    stashes = await service.stashes(root);
    expect(stashes.map((s) => s.message)).toEqual(["WIP: native Git actions"]);
    files = await service.changes(root);
    expect(files.length).toBeGreaterThan(0);
    await service.dropStash(stashes[0], root);
    expect(await service.stashes(root)).toEqual([]);
    await expect((async () => { await service.stash("Nothing", false, root); await service.stash("Nothing", false, root); })()).rejects.toThrow(/no changes/);
  });

  it("publishes, then tracks, and never forces a push", async () => {
    const remote = await Repository.make(roots, true);
    const repo = await Repository.make(roots);
    const service = new GitService(), root = repo.root;
    repo.write("a.txt", "one\n");
    await repo.commitAll("one");
    let status = await service.upstreamStatus(root);
    expect(pushRemote(status)).toBeUndefined(); expect(canPush(status)).toBe(false);
    await expect(service.push(root)).rejects.toThrow(/no remote/);
    await repo.run(["remote", "add", "origin", remote.root]);
    await repo.run(["checkout", "--quiet", "-b", "feature/native-git"]);
    status = await service.upstreamStatus(root);
    expect(status.branch).toBe("feature/native-git"); expect(status.upstream).toBeUndefined();
    expect(publishes(status)).toBe(true); expect(status.ahead).toBe(1); expect(canPush(status)).toBe(true);
    await service.push(root);
    status = await service.upstreamStatus(root);
    expect(status.upstream).toBe("origin/feature/native-git"); expect(status.upstreamRemote).toBe("origin");
    expect(status.ahead).toBe(0); expect(canPush(status)).toBe(false);
    repo.write("a.txt", "two\n");
    await repo.commitAll("two");
    status = await service.upstreamStatus(root);
    expect(status.ahead).toBe(1); expect(canPush(status)).toBe(true);
    await service.push(root);
    const remoteHead = await remote.run(["rev-parse", "refs/heads/feature/native-git"]);
    expect(remoteHead).toBe(await repo.run(["rev-parse", "HEAD"]));
    await repo.run(["reset", "--quiet", "--hard", "HEAD~1"]);
    repo.write("a.txt", "diverged\n");
    await repo.commitAll("diverged");
    const diverged = await repo.run(["rev-parse", "HEAD"]);
    await expect(service.push(root)).rejects.toThrow();
    expect(await repo.run(["rev-parse", "HEAD"])).toBe(diverged);
    expect(await remote.run(["rev-parse", "refs/heads/feature/native-git"])).toBe(remoteHead);
    expect((await service.remoteBranches("origin", root)).branches).toEqual(["feature/native-git"]);
  });

  it("fast-forwards only and refuses diverged or conflicting updates", async () => {
    const remote = await Repository.make(roots, true);
    const repo = await Repository.make(roots), other = await Repository.make(roots);
    const service = new GitService();
    repo.write("a.txt", "one\n");
    await repo.commitAll("one");
    await repo.run(["remote", "add", "origin", remote.root]);
    await expect(service.pull(repo.root)).rejects.toThrow(/Push it first/);
    await service.push(repo.root);
    await other.run(["remote", "add", "origin", remote.root]);
    await other.run(["fetch", "--quiet", "origin"]);
    await other.run(["switch", "--quiet", "-C", "main", "origin/main"]);
    other.write("a.txt", "one\ntwo\n");
    await other.commitAll("two");
    await other.run(["push", "--quiet", "origin", "main"]);
    await service.fetch(repo.root);
    let status = await service.upstreamStatus(repo.root);
    expect([status.behind, status.ahead]).toEqual([1, 0]);
    repo.write("a.txt", "local edit\n");
    await expect(service.pull(repo.root)).rejects.toThrow();
    expect(repo.read("a.txt")).toBe("local edit\n");
    await repo.run(["checkout", "--", "a.txt"]);
    await service.pull(repo.root);
    expect(repo.read("a.txt")).toBe("one\ntwo\n");
    status = await service.upstreamStatus(repo.root);
    expect(status.behind).toBe(0);
    other.write("a.txt", "one\ntwo\nthree\n");
    await other.commitAll("three");
    await other.run(["push", "--quiet", "origin", "main"]);
    repo.write("b.txt", "local\n");
    await repo.commitAll("local");
    const head = await repo.run(["rev-parse", "HEAD"]);
    await expect(service.pull(repo.root)).rejects.toThrow();
    expect(await repo.run(["rev-parse", "HEAD"])).toBe(head);
    expect(existsSync(join(repo.root, ".git/MERGE_HEAD"))).toBe(false);
  });

  it("loads all changes in order with a line limit", async () => {
    const repo = await Repository.make(roots);
    for (const name of ["a", "b", "c"]) repo.write(`${name}.txt`, "base\n");
    await repo.commitAll("base");
    repo.write("a.txt", Array.from({ length: 6 }, (_, i) => `a${i + 1}`).join("\n") + "\n");
    await repo.run(["add", "a.txt"]);
    repo.write("b.txt", "changed\n");
    repo.write("c.txt", "changed\n");
    repo.write("new.txt", "untracked\n");
    const service = new GitService(), root = repo.root;
    const files = await service.changes(root);
    const entries: { file: ChangedFile; scope: DiffScope }[] = [
      ...files.filter(hasStaged).map((file) => ({ file, scope: "staged" as const })),
      ...files.filter((f) => f.worktreeStatus !== " ").map((file) => ({ file, scope: "working" as const })),
    ];
    const all = await service.snapshots(entries, newID(), root);
    expect(all.map((s) => s.path)).toEqual(["a.txt", "b.txt", "c.txt", "new.txt"]);
    expect(all.map((s) => s.scope)).toEqual(["staged", "working", "working", "working"]);
    expect(all.every((s) => s.lines.length > 0 && s.notice === undefined)).toBe(true);
    const limited = await service.snapshots(entries, newID(), root, 5);
    expect(limited[0].lines.length).toBeGreaterThan(0);
    expect(limited.slice(1).map((s) => s.notice)).toEqual([GitService.deferredNotice, GitService.deferredNotice, GitService.deferredNotice]);
    const broken = [...entries, { file: { path: "../outside", indexStatus: "?", worktreeStatus: "?" }, scope: "working" as const }];
    const withError = await service.snapshots(broken, newID(), root);
    expect(withError.length).toBe(5);
    expect(withError.at(-1)?.notice).toBeDefined();
    expect(withError[1].lines.length).toBeGreaterThan(0);
  });

  it("parses tracking, stash subjects and pull request numbers", () => {
    expect(GitService.parseTrack("ahead 2, behind 1")).toEqual({ ahead: 2, behind: 1, gone: false });
    expect(GitService.parseTrack("behind 3")).toEqual({ ahead: 0, behind: 3, gone: false });
    expect(GitService.parseTrack("gone")).toEqual({ ahead: 0, behind: 0, gone: true });
    expect(GitService.parseTrack("")).toEqual({ ahead: 0, behind: 0, gone: false });
    const stashes = GitService.parseStashes("abc\u001fstash@{0}\u001f1700000000\u001fOn feat/x: Name: with colon\ndef\u001fstash@{1}\u001f1700000001\u001fWIP on (no branch): 1234567 subject\nbad line\n");
    expect(stashes.map((s) => s.message)).toEqual(["Name: with colon", "1234567 subject"]);
    expect(stashes.map((s) => s.branch)).toEqual(["feat/x", undefined]);
    expect(stashes.map(stashReference)).toEqual(["stash@{0}", "stash@{1}"]);
    expect(PullRequests.number("https://github.com/o/r/pull/42")).toBe(42);
    expect(PullRequests.number("https://github.com/o/r")).toBeUndefined();
  });

  it("describes only the index in staged changes and cuts long patches", async () => {
    const repo = await Repository.make(roots);
    const service = new GitService();
    repo.write("a.txt", "one\n");
    await repo.run(["add", "a.txt"]);
    const unborn = await service.stagedChanges(repo.root);
    expect(unborn.stat).toContain("a.txt");
    expect(unborn.recentSubjects).toEqual([]);
    await repo.commitAll("Add a");
    repo.write("a.txt", "one\ntwo\n");
    repo.write("b.txt", "unstaged\n");
    await repo.run(["add", "a.txt"]);
    const changes = await service.stagedChanges(repo.root);
    expect(changes.stat).toContain("a.txt");
    expect(changes.stat.includes("b.txt") || changes.patch.includes("unstaged")).toBe(false);
    expect(changes.patch).toContain("+two");
    expect(changes.truncated).toBe(false);
    expect(changes.recentSubjects).toEqual(["Add a"]);
    const cut = await service.stagedChanges(repo.root, 40);
    expect(cut.truncated).toBe(true);
    expect(cut.patch.length).toBeLessThanOrEqual(40);
    expect(cut.patch.endsWith("\n")).toBe(false);
    expect(changes.patch.startsWith(cut.patch)).toBe(true);
  });
});
